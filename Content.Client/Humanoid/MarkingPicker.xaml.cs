// Ganimed-Edit: classic marking picker (category dropdown, unused/used lists, rank up/down, colors).
// It works on top of the Nubody MarkingsViewModel: a "category" here is one (organ, layer) slot of the model.
[GenerateTypedNameReferences]
public sealed partial class MarkingPicker : Control
{
    private static readonly IReadOnlyDictionary<string, MarkingPrototype> EmptyMarkings =
        new Dictionary<string, MarkingPrototype>();

    [Dependency] private readonly MarkingManager _marking = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IEntityManager _entity = default!;

    private readonly SpriteSystem _sprite;

    private MarkingsViewModel? _model;

    private readonly List<MarkingSlot> _slots = new();
    private int _currentSlot = -1;

    // Marking selected in the "used" list, kept across refreshes.
    private string? _selectedUsed;

    // Set while the picker itself changes a color so the sliders are not rebuilt under the user's mouse.
    private bool _changingColor;

    private HashSet<HumanoidVisualLayers> _ignoredLayers = new();
    private string _ignoreLayers = string.Empty;

    private readonly record struct MarkingSlot(ProtoId<OrganCategoryPrototype> Organ, HumanoidVisualLayers Layer, string Title);

    /// <summary>
    /// Comma separated list of <see cref="HumanoidVisualLayers"/> that are not shown in this picker
    /// (for example hair, which has its own picker on the appearance tab).
    /// </summary>
    public string IgnoreLayers
    {
        get => _ignoreLayers;
        set
        {
            _ignoreLayers = value;
            _ignoredLayers = new HashSet<HumanoidVisualLayers>();

            foreach (var part in value.Split(','))
            {
                if (Enum.TryParse(part.Trim(), out HumanoidVisualLayers layer))
                    _ignoredLayers.Add(layer);
            }

            RebuildSlots();
        }
    }

    public MarkingPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entity.System<SpriteSystem>();

        CategoryButton.OnItemSelected += OnCategorySelected;
        SearchBar.OnTextChanged += _ => PopulateUnused();
        UsedList.OnItemSelected += OnUsedSelected;
        AddButton.OnPressed += _ => AddSelected();
        RemoveButton.OnPressed += _ => RemoveSelected();
        RankUpButton.OnPressed += _ => MoveSelected(-1);
        RankDownButton.OnPressed += _ => MoveSelected(1);

        RebuildSlots();
    }

    public void SetModel(MarkingsViewModel model)
    {
        if (ReferenceEquals(_model, model))
            return;

        if (IsInsideTree)
            Unsubscribe();

        _model = model;

        if (IsInsideTree)
            Subscribe();

        RebuildSlots();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        Subscribe();
        RebuildSlots();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        Unsubscribe();
    }

    private void Subscribe()
    {
        if (_model == null)
            return;

        _model.OrganDataChanged += RebuildSlots;
        _model.EnforcementsChanged += RebuildSlots;
        _model.OrganProfileDataChanged += OnOrganProfileDataChanged;
        _model.MarkingsReset += OnMarkingsReset;
        _model.MarkingsChanged += OnMarkingsChanged;
    }

    private void Unsubscribe()
    {
        if (_model == null)
            return;

        _model.OrganDataChanged -= RebuildSlots;
        _model.EnforcementsChanged -= RebuildSlots;
        _model.OrganProfileDataChanged -= OnOrganProfileDataChanged;
        _model.MarkingsReset -= OnMarkingsReset;
        _model.MarkingsChanged -= OnMarkingsChanged;
    }

    private void OnOrganProfileDataChanged(bool refresh)
    {
        // The set of possible markings (sex, group) may have changed.
        if (refresh)
            RebuildSlots();
    }

    private void OnMarkingsReset()
    {
        RefreshLists();
    }

    private void OnMarkingsChanged(ProtoId<OrganCategoryPrototype> organ, HumanoidVisualLayers layer)
    {
        if (_changingColor)
            return;

        if (!TryGetSlot(out var currentOrgan, out var currentLayer) || currentOrgan != organ || currentLayer != layer)
            return;

        RefreshLists();
    }

    #region Slots

    private void RebuildSlots()
    {
        MarkingSlot? previous = _currentSlot >= 0 && _currentSlot < _slots.Count ? _slots[_currentSlot] : null;

        _slots.Clear();
        CategoryButton.Clear();
        _currentSlot = -1;

        if (_model != null)
        {
            var raw = new List<MarkingSlot>();

            foreach (var (organ, organData) in _model.OrganData)
            {
                foreach (var layer in organData.Layers)
                {
                    if (_ignoredLayers.Contains(layer))
                        continue;

                    var hasMarkings = (_model.SelectedMarkings(organ, layer)?.Count ?? 0) > 0;
                    if (GetCandidates(organ, layer).Count == 0 && !hasMarkings)
                        continue;

                    raw.Add(new MarkingSlot(organ, layer, GetLayerTitle(layer, organData.Group)));
                }
            }

            // The same layer can exist on several organs, tell them apart by the organ name.
            var duplicated = raw.GroupBy(slot => slot.Title)
                .Where(group => group.Count() > 1)
                .Select(group => group.Key)
                .ToHashSet();

            foreach (var slot in raw.OrderBy(slot => (int) slot.Layer).ThenBy(slot => slot.Organ.Id))
            {
                var title = duplicated.Contains(slot.Title)
                    ? $"{slot.Title} ({GetOrganName(slot.Organ)})"
                    : slot.Title;

                CategoryButton.AddItem(title, _slots.Count);
                _slots.Add(slot with { Title = title });
            }
        }

        if (_slots.Count > 0)
        {
            var index = 0;
            if (previous is { } prev)
            {
                var found = _slots.FindIndex(slot => slot.Organ == prev.Organ && slot.Layer == prev.Layer);
                if (found != -1)
                    index = found;
            }

            _currentSlot = index;
            CategoryButton.SelectId(index);
        }

        CategoryButton.Visible = _slots.Count > 1;
        RefreshLists();
    }

    private void OnCategorySelected(OptionButton.ItemSelectedEventArgs args)
    {
        CategoryButton.SelectId(args.Id);
        _currentSlot = args.Id;
        _selectedUsed = null;
        RefreshLists();
    }

    private bool TryGetSlot(out ProtoId<OrganCategoryPrototype> organ, out HumanoidVisualLayers layer)
    {
        if (_currentSlot >= 0 && _currentSlot < _slots.Count)
        {
            organ = _slots[_currentSlot].Organ;
            layer = _slots[_currentSlot].Layer;
            return true;
        }

        organ = default;
        layer = default;
        return false;
    }

    private static string GetLayerTitle(HumanoidVisualLayers layer, ProtoId<MarkingsGroupPrototype> group)
    {
        if (Loc.TryGetString($"markings-layer-{layer}-{group.Id}", out var groupTitle))
            return groupTitle;

        return Loc.TryGetString($"markings-layer-{layer}", out var title) ? title : layer.ToString();
    }

    private static string GetOrganName(ProtoId<OrganCategoryPrototype> organ)
    {
        return Loc.TryGetString($"markings-organ-{organ.Id}", out var name) ? name : organ.Id;
    }

    private IReadOnlyDictionary<string, MarkingPrototype> GetCandidates(ProtoId<OrganCategoryPrototype> organ, HumanoidVisualLayers layer)
    {
        if (_model == null || !_model.OrganData.TryGetValue(organ, out var organData))
            return EmptyMarkings;

        if (_model.EnforceGroupAndSexRestrictions && _model.OrganProfileData.TryGetValue(organ, out var profile))
            return _marking.MarkingsByLayerAndGroupAndSex(layer, organData.Group, profile.Sex);

        return _marking.MarkingsByLayer(layer);
    }

    #endregion

    #region Lists

    private void RefreshLists()
    {
        PopulateUnused();
        PopulateUsed();
        UpdatePoints();
        UpdateButtons();
        PopulateColors();
    }

    private static string GetMarkingName(MarkingPrototype proto)
    {
        return Loc.TryGetString($"marking-{proto.ID}", out var name) ? name : proto.ID;
    }

    private Texture? GetIcon(MarkingPrototype proto)
    {
        return proto.Sprites.Count > 0 ? _sprite.Frame0(proto.Sprites[0]) : null;
    }

    private void PopulateUnused()
    {
        UnusedList.Clear();

        if (_model == null || !TryGetSlot(out var organ, out var layer))
            return;

        var filter = SearchBar.Text.Trim();

        foreach (var proto in GetCandidates(organ, layer).Values.OrderBy(GetMarkingName))
        {
            if (_model.IsMarkingSelected(organ, layer, proto.ID))
                continue;

            var name = GetMarkingName(proto);
            if (filter.Length > 0 &&
                !name.Contains(filter, StringComparison.OrdinalIgnoreCase) &&
                !proto.ID.Contains(filter, StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            // Corvax-Sponsors-Start
            if (proto.SponsorOnly)
                name += GetSponsorOnlySuffix();
            // Corvax-Sponsors-End

            var item = UnusedList.AddItem(name, GetIcon(proto));
            item.Metadata = proto.ID;
        }
    }

    private void PopulateUsed()
    {
        UsedList.Clear();

        if (_model == null || !TryGetSlot(out var organ, out var layer))
            return;

        var used = _model.SelectedMarkings(organ, layer);
        if (used == null)
            return;

        foreach (var marking in used)
        {
            if (!_prototype.TryIndex(marking.MarkingId, out var proto))
                continue;

            var text = Loc.GetString(marking.Forced ? "marking-used-forced" : "marking-used",
                ("marking-name", GetMarkingName(proto)));

            var item = UsedList.AddItem(text, GetIcon(proto));
            item.Metadata = proto.ID;

            if (_selectedUsed == proto.ID)
                item.Selected = true;
        }
    }

    private void UpdatePoints()
    {
        if (_model == null || !TryGetSlot(out var organ, out var layer))
        {
            MarkingPoints.Text = string.Empty;
            return;
        }

        _model.GetMarkingCounts(organ, layer, out var isRequired, out var count, out var selected);
        MarkingPoints.Text = Loc.GetString("markings-limits",
            ("required", isRequired),
            ("count", count),
            ("selectable", count - selected));
    }

    private void UpdateButtons()
    {
        var hasSlot = _model != null && TryGetSlot(out _, out _);

        AddButton.Disabled = !hasSlot;
        RemoveButton.Disabled = !hasSlot || UsedList.Count == 0;
        RankUpButton.Disabled = !hasSlot || UsedList.Count < 2;
        RankDownButton.Disabled = !hasSlot || UsedList.Count < 2;
    }

    private static string? GetSelectedId(ItemList list)
    {
        for (var i = 0; i < list.Count; i++)
        {
            if (list[i].Selected)
                return list[i].Metadata as string;
        }

        return null;
    }

    private void OnUsedSelected(ItemList.ItemListSelectedEventArgs args)
    {
        _selectedUsed = UsedList[args.ItemIndex].Metadata as string;
        PopulateColors();
    }

    #endregion

    #region Actions

    private void AddSelected()
    {
        if (_model == null || !TryGetSlot(out var organ, out var layer))
            return;

        var id = GetSelectedId(UnusedList);
        if (id == null)
            return;

        if (_model.TrySelectMarking(organ, layer, id))
            _selectedUsed = id;

        // The model raises MarkingsChanged on success, refresh anyway so a rejected add resets the lists.
        RefreshLists();
    }

    private void RemoveSelected()
    {
        if (_model == null || !TryGetSlot(out var organ, out var layer))
            return;

        var id = _selectedUsed ?? GetSelectedId(UsedList);
        if (id == null)
            return;

        if (_model.TryDeselectMarking(organ, layer, id))
            _selectedUsed = null;

        RefreshLists();
    }

    private void MoveSelected(int places)
    {
        if (_model == null || !TryGetSlot(out var organ, out var layer))
            return;

        var id = _selectedUsed ?? GetSelectedId(UsedList);
        var used = _model.SelectedMarkings(organ, layer);
        if (id == null || used == null)
            return;

        var index = used.FindIndex(marking => marking.MarkingId == id);
        var destination = index + places;
        if (index < 0 || destination < 0 || destination >= used.Count)
            return;

        _model.ChangeMarkingOrder(organ,
            layer,
            id,
            places < 0 ? CandidatePosition.Before : CandidatePosition.After,
            destination);

        _selectedUsed = id;
        RefreshLists();
    }

    #endregion

    #region Colors

    private void PopulateColors()
    {
        ColorsContainer.RemoveAllChildren();
        ColorScroll.Visible = false;

        if (_model == null || _selectedUsed == null || !TryGetSlot(out var organ, out var layer))
            return;

        if (!_prototype.TryIndex<MarkingPrototype>(_selectedUsed, out var proto))
            return;

        if (!_model.IsMarkingColorCustomizable(organ, layer, proto.ID))
            return;

        if (_model.GetMarking(organ, layer, proto.ID) is not { } marking)
            return;

        var model = _model;
        var markingId = proto.ID;

        for (var i = 0; i < proto.Sprites.Count && i < marking.MarkingColors.Count; i++)
        {
            var container = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                HorizontalExpand = true,
            };

            var selector = new LegacyColorSelectorSliders
            {
                HorizontalExpand = true,
                Color = marking.MarkingColors[i],
            };

            container.AddChild(new Label { Text = GetColorLabel(proto, i) });
            container.AddChild(selector);
            ColorsContainer.AddChild(container);

            var colorIndex = i;
            selector.OnColorChanged += color =>
            {
                _changingColor = true;
                try
                {
                    model.TrySetMarkingColor(organ, layer, markingId, colorIndex, color);
                }
                finally
                {
                    _changingColor = false;
                }
            };
        }

        ColorScroll.Visible = ColorsContainer.ChildCount > 0;
    }

    private static string GetColorLabel(MarkingPrototype proto, int index)
    {
        var state = proto.Sprites[index] switch
        {
            SpriteSpecifier.Rsi rsi => rsi.RsiState,
            SpriteSpecifier.Texture texture => texture.TexturePath.Filename,
            _ => string.Empty,
        };

        return Loc.TryGetString($"marking-{proto.ID}-{state}", out var label)
            ? label
            : Loc.GetString("marking-used", ("marking-name", GetMarkingName(proto)));
    }

    #endregion
}
