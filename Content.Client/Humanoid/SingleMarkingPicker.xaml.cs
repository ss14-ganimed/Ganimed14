using System.Linq;
using Content.Client.ADT.UserInterface.Controls;
using Content.Shared.Body;
using Content.Shared.Humanoid;
using Content.Shared.Humanoid.Markings;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;
using static Content.Client.Corvax.SponsorOnlyHelpers; // Corvax-Sponsors

namespace Content.Client.Humanoid;

// Ganimed-Edit: classic picker for a single marking layer (hair, facial hair) on top of the Nubody MarkingsViewModel.
// One marking of the layer can be chosen from the list, "none" removes it when the layer is not required.
[GenerateTypedNameReferences]
public sealed partial class SingleMarkingPicker : BoxContainer
{
    private static readonly IReadOnlyDictionary<string, MarkingPrototype> EmptyMarkings =
        new Dictionary<string, MarkingPrototype>();

    [Dependency] private readonly MarkingManager _marking = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IEntityManager _entity = default!;

    private readonly SpriteSystem _sprite;

    private MarkingsViewModel? _model;
    private HumanoidVisualLayers _layer = HumanoidVisualLayers.Hair;

    private bool _ignoreItemSelected;

    // Set while the picker itself changes a color so the sliders are not rebuilt under the user's mouse.
    private bool _changingColor;

    /// <summary>
    /// The visual layer whose markings this picker edits.
    /// </summary>
    public HumanoidVisualLayers Layer
    {
        get => _layer;
        set
        {
            _layer = value;
            CategoryName.Text = Loc.TryGetString($"markings-layer-{_layer}", out var title) ? title : _layer.ToString();
            Refresh();
        }
    }

    public SingleMarkingPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entity.System<SpriteSystem>();

        MarkingList.OnItemSelected += SelectMarking;
        Search.OnTextChanged += _ => PopulateList();

        CategoryName.Text = Loc.TryGetString($"markings-layer-{_layer}", out var title) ? title : _layer.ToString();
        Refresh();
    }

    public void SetModel(MarkingsViewModel model)
    {
        if (ReferenceEquals(_model, model))
            return;

        if (IsInsideTree)
            Unsubscribe();

        _model = model;

        if (IsInsideTree)
            Subscribe();

        Refresh();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        Subscribe();
        Refresh();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        Unsubscribe();
    }

    private void Subscribe()
    {
        if (_model == null)
            return;

        _model.OrganDataChanged += Refresh;
        _model.EnforcementsChanged += Refresh;
        _model.OrganProfileDataChanged += OnOrganProfileDataChanged;
        _model.MarkingsReset += Refresh;
        _model.MarkingsChanged += OnMarkingsChanged;
    }

    private void Unsubscribe()
    {
        if (_model == null)
            return;

        _model.OrganDataChanged -= Refresh;
        _model.EnforcementsChanged -= Refresh;
        _model.OrganProfileDataChanged -= OnOrganProfileDataChanged;
        _model.MarkingsReset -= Refresh;
        _model.MarkingsChanged -= OnMarkingsChanged;
    }

    private void OnOrganProfileDataChanged(bool refresh)
    {
        // The set of possible markings (sex, group) may have changed.
        if (refresh)
            Refresh();
    }

    private void OnMarkingsChanged(ProtoId<OrganCategoryPrototype> organ, HumanoidVisualLayers layer)
    {
        if (_changingColor || layer != _layer)
            return;

        Refresh();
    }

    private bool TryGetOrgan(out ProtoId<OrganCategoryPrototype> organ)
    {
        if (_model != null)
        {
            foreach (var (key, data) in _model.OrganData)
            {
                if (data.Layers.Contains(_layer))
                {
                    organ = key;
                    return true;
                }
            }
        }

        organ = default;
        return false;
    }

    private IReadOnlyDictionary<string, MarkingPrototype> GetCandidates(ProtoId<OrganCategoryPrototype> organ)
    {
        if (_model == null || !_model.OrganData.TryGetValue(organ, out var organData))
            return EmptyMarkings;

        if (_model.EnforceGroupAndSexRestrictions && _model.OrganProfileData.TryGetValue(organ, out var profile))
            return _marking.MarkingsByLayerAndGroupAndSex(_layer, organData.Group, profile.Sex);

        return _marking.MarkingsByLayer(_layer);
    }

    private string? GetCurrentId(ProtoId<OrganCategoryPrototype> organ)
    {
        var used = _model?.SelectedMarkings(organ, _layer);
        return used != null && used.Count > 0 ? used[0].MarkingId.Id : null;
    }

    private void Refresh()
    {
        if (!TryGetOrgan(out var organ) || GetCandidates(organ).Count == 0)
        {
            Visible = false;
            return;
        }

        Visible = true;
        PopulateList();
        PopulateColors();
    }

    private static string GetMarkingName(MarkingPrototype proto)
    {
        return Loc.TryGetString($"marking-{proto.ID}", out var name) ? name : proto.ID;
    }

    private void PopulateList()
    {
        MarkingList.Clear();

        if (_model == null || !TryGetOrgan(out var organ))
            return;

        var filter = Search.Text.Trim();
        var current = GetCurrentId(organ);

        _model.GetMarkingCounts(organ, _layer, out var isRequired, out _, out _);

        _ignoreItemSelected = true;

        if (!isRequired && filter.Length == 0)
        {
            var none = MarkingList.AddItem(Loc.GetString("markings-none"));
            none.Metadata = string.Empty;
            none.Selected = current == null;
        }

        foreach (var proto in GetCandidates(organ).Values.OrderBy(GetMarkingName))
        {
            var name = GetMarkingName(proto);
            if (filter.Length > 0 &&
                !name.Contains(filter, StringComparison.OrdinalIgnoreCase) &&
                !proto.ID.Contains(filter, StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            // Corvax-Sponsors-Start
            if (proto.SponsorOnly)
                name += GetSponsorOnlySuffix();
            // Corvax-Sponsors-End

            var icon = proto.Sprites.Count > 0 ? _sprite.Frame0(proto.Sprites[0]) : null;
            var item = MarkingList.AddItem(name, icon);
            item.Metadata = proto.ID;
            item.Selected = current == proto.ID;
        }

        _ignoreItemSelected = false;
    }

    private void SelectMarking(ItemList.ItemListSelectedEventArgs args)
    {
        if (_ignoreItemSelected || _model == null || !TryGetOrgan(out var organ))
            return;

        var id = MarkingList[args.ItemIndex].Metadata as string;
        if (id == null)
            return;

        var used = _model.SelectedMarkings(organ, _layer)?.ToList() ?? new List<Marking>();

        if (id.Length == 0)
        {
            // "None": drop everything on this layer (fails silently when the layer is required).
            foreach (var marking in used)
            {
                _model.TryDeselectMarking(organ, _layer, marking.MarkingId);
            }
        }
        else
        {
            if (used.Count == 1 && used[0].MarkingId.Id == id)
                return;

            // Drop the previous choice first, the model itself replaces it when the layer limit is one.
            foreach (var marking in used)
            {
                if (marking.MarkingId.Id != id)
                    _model.TryDeselectMarking(organ, _layer, marking.MarkingId);
            }

            _model.TrySelectMarking(organ, _layer, id);
        }

        Refresh();
    }

    private void PopulateColors()
    {
        ColorSelectorContainer.RemoveAllChildren();
        ColorScroll.Visible = false;

        if (_model == null || !TryGetOrgan(out var organ))
            return;

        var currentId = GetCurrentId(organ);
        if (currentId == null || !_prototype.TryIndex<MarkingPrototype>(currentId, out var proto))
            return;

        if (!_model.IsMarkingColorCustomizable(organ, _layer, proto.ID))
            return;

        if (_model.GetMarking(organ, _layer, proto.ID) is not { } marking)
            return;

        var model = _model;
        var layer = _layer;
        var markingId = proto.ID;

        for (var i = 0; i < proto.Sprites.Count && i < marking.MarkingColors.Count; i++)
        {
            var selector = new LegacyColorSelectorSliders
            {
                HorizontalExpand = true,
                Color = marking.MarkingColors[i],
            };

            ColorSelectorContainer.AddChild(selector);

            var colorIndex = i;
            selector.OnColorChanged += color =>
            {
                _changingColor = true;
                try
                {
                    model.TrySetMarkingColor(organ, layer, markingId, colorIndex, color);
                }
                finally
                {
                    _changingColor = false;
                }
            };
        }

        ColorScroll.Visible = ColorSelectorContainer.ChildCount > 0;
    }
}
